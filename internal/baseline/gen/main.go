// Command gen rewrites data_gen.go from the JSON baselines. Run it with go generate.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

type predicate struct {
	Eq  *int64  `json:"eq"`
	In  []int64 `json:"in"`
	Gte *int64  `json:"gte"`
}

type sysctlCheck struct {
	Key       string    `json:"key"`
	Expect    predicate `json:"expect"`
	Severity  string    `json:"severity"`
	Rationale string    `json:"rationale"`
}

type selinuxCheck struct {
	Key       string `json:"key"`
	Expect    string `json:"expect"`
	Severity  string `json:"severity"`
	Rationale string `json:"rationale"`
}

var severities = map[string]string{
	"info":     "check.Info",
	"low":      "check.Low",
	"medium":   "check.Medium",
	"high":     "check.High",
	"critical": "check.Critical",
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "baseline gen:", err)
		os.Exit(1)
	}
}

func run() error {
	var sysctl struct {
		Checks []sysctlCheck `json:"checks"`
	}
	if err := read("data/sysctl.json", &sysctl); err != nil {
		return err
	}
	var selinux struct {
		Checks []selinuxCheck `json:"checks"`
	}
	if err := read("data/selinux.json", &selinux); err != nil {
		return err
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	out.WriteString("package baseline\n\n")
	out.WriteString("import \"github.com/YarBurArt/kishirika/internal/check\"\n\n")

	if err := writeSysctl(&out, sysctl.Checks); err != nil {
		return err
	}
	if err := writeSELinux(&out, selinux.Checks); err != nil {
		return err
	}

	src, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	return os.WriteFile("data_gen.go", src, 0o600)
}

func read(name string, dst any) error {
	raw, err := os.ReadFile(name)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(raw, dst); err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	return nil
}

func writeSysctl(out *bytes.Buffer, checks []sysctlCheck) error {
	if len(checks) == 0 {
		return errors.New("sysctl.json: no checks")
	}

	out.WriteString("var sysctlChecks = []SysctlCheck{\n")
	seen := make(map[string]bool, len(checks))
	for i, c := range checks {
		switch {
		case c.Key == "":
			return fmt.Errorf("sysctl.json check %d: key is required", i)
		case seen[c.Key]:
			return fmt.Errorf("sysctl.json: duplicate key %q", c.Key)
		}
		seen[c.Key] = true

		expect, err := predicateExpr(c.Expect)
		if err != nil {
			return fmt.Errorf("%s: %w", c.Key, err)
		}
		severity, ok := severities[c.Severity]
		if !ok {
			return fmt.Errorf("%s: unknown severity %q", c.Key, c.Severity)
		}

		fmt.Fprintf(out, "\t{\n\t\tKey: %q,\n\t\tExpect: %s,\n\t\tSeverity: %s,\n\t\tRationale: %q,\n\t},\n",
			c.Key, expect, severity, c.Rationale)
	}
	out.WriteString("}\n\n")
	return nil
}

func writeSELinux(out *bytes.Buffer, checks []selinuxCheck) error {
	if len(checks) == 0 {
		return errors.New("selinux.json: no checks")
	}

	out.WriteString("var selinuxChecks = []SELinuxCheck{\n")
	seen := make(map[string]bool, len(checks))
	for i, c := range checks {
		switch {
		case c.Key == "":
			return fmt.Errorf("selinux.json check %d: key is required", i)
		case seen[c.Key]:
			return fmt.Errorf("selinux.json: duplicate key %q", c.Key)
		case c.Expect != "on" && c.Expect != "off":
			return fmt.Errorf("%s: expect must be on or off, got %q", c.Key, c.Expect)
		}
		seen[c.Key] = true

		severity, ok := severities[c.Severity]
		if !ok {
			return fmt.Errorf("%s: unknown severity %q", c.Key, c.Severity)
		}

		fmt.Fprintf(out, "\t{\n\t\tKey: %q,\n\t\tExpect: %q,\n\t\tSeverity: %s,\n\t\tRationale: %q,\n\t},\n",
			c.Key, c.Expect, severity, c.Rationale)
	}
	out.WriteString("}\n\n")
	return nil
}

func predicateExpr(p predicate) (string, error) {
	set := 0
	if p.Eq != nil {
		set++
	}
	if len(p.In) > 0 {
		set++
	}
	if p.Gte != nil {
		set++
	}
	if set != 1 {
		return "", errors.New("expect must set exactly one of eq, in, gte")
	}

	switch {
	case p.Eq != nil:
		return fmt.Sprintf("eq(%d)", *p.Eq), nil
	case p.Gte != nil:
		return fmt.Sprintf("gte(%d)", *p.Gte), nil
	}

	values := make([]string, len(p.In))
	for i, value := range p.In {
		values[i] = strconv.FormatInt(value, 10)
	}
	return "check.Predicate{In: []int64{" + strings.Join(values, ", ") + "}}", nil
}
